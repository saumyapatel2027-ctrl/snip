// Regenerates supabase/seed.sql from lib/demo-data.json.  Usage: node scripts/gen-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const studios = JSON.parse(readFileSync(new URL("../lib/demo-data.json", import.meta.url), "utf8"));
const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${(a ?? []).map(q).join(", ")}]::text[]`;

let sql = `-- Snip demo listings (8 Delhi studios). Generated by scripts/gen-seed.mjs — safe to re-run.
-- Seeded studios have no owner account; admins can manage them from /admin.

`;
for (const s of studios) {
  sql += `insert into public.studios (slug, name, kind, tagline, bio, area, address, lat, lng, phone, email, instagram, categories, starting_price, home_visits, studio_visits, cover_url, photos, status, plan, snip_code)
values (${q(s.slug)}, ${q(s.name)}, ${q(s.kind)}, ${q(s.tagline)}, ${q(s.bio)}, ${q(s.area)}, ${q(s.address)}, ${s.lat}, ${s.lng}, ${q(s.phone)}, ${q(s.email)}, ${q(s.instagram)}, ${arr(s.categories)}, ${s.starting_price}, ${s.home_visits}, ${s.studio_visits}, ${q(s.cover_url)}, ${arr(s.photos)}, 'verified', ${q(s.plan)}, ${q(s.snip_code)})
on conflict (slug) do nothing;
`;
  sql += `delete from public.services where studio_id = (select id from public.studios where slug = ${q(s.slug)}) and not exists (select 1 from public.bookings b where b.service_id = services.id);\n`;
  s.services.forEach((v, i) => {
    sql += `insert into public.services (studio_id, name, description, price, duration_mins, sort) select id, ${q(v.name)}, ${q(v.description)}, ${v.price}, ${v.duration_mins}, ${i} from public.studios where slug = ${q(s.slug)};\n`;
  });
  sql += `delete from public.reviews where booking_id is null and studio_id = (select id from public.studios where slug = ${q(s.slug)});\n`;
  for (const r of s.reviews) {
    sql += `insert into public.reviews (studio_id, author_name, rating, comment) select id, ${q(r.author_name)}, ${r.rating}, ${q(r.comment)} from public.studios where slug = ${q(s.slug)};\n`;
  }
  // Keep the headline rating from the demo data (it reflects reviews collected before Snip).
  sql += `update public.studios set rating = ${s.rating}, review_count = ${s.review_count} where slug = ${q(s.slug)};\n\n`;
}
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote supabase/seed.sql (${studios.length} studios)`);
